export const SUPPORTED_LANGUAGES = ['it', 'en']

export function detectDeviceLanguage() {
  const raw = (typeof navigator !== 'undefined' && navigator.language) || 'en'
  return raw.toLowerCase().startsWith('it') ? 'it' : 'en'
}
